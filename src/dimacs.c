// dimacs.c - DIMACS CNF file parsing and serialization
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <ctype.h>
#include "dimacs.h"

#define MAX_LINE_BUFFER 4096

logisat_status_t dimacs_load_from_file(const char *filepath, cnf_formula_t **out_formula) {
    if (!filepath || !out_formula) return LOGISAT_ERR_NULL_PTR;
    *out_formula = NULL;

    FILE *fp = fopen(filepath, "r");
    if (!fp) return LOGISAT_ERR_FILE_IO;

    char line[MAX_LINE_BUFFER];
    bool header_found = false;
    size_t expected_vars = 0;
    size_t expected_clauses = 0;
    cnf_formula_t *formula = NULL;
    clause_t *current_clause = NULL;

    while (fgets(line, sizeof(line), fp)) {
        char *ptr = line;
        while (isspace((unsigned char)*ptr)) ptr++;
        if (*ptr == '\0') continue;
        if (*ptr == 'c' || *ptr == 'C') continue;

        if (*ptr == 'p' || *ptr == 'P') {
            if (header_found) {
                fclose(fp);
                if (formula) cnf_formula_destroy(formula);
                return LOGISAT_ERR_DIMACS_FORMAT;
            }

            char format[32] = {0};
            int n_vars = 0, n_clauses = 0;
            if (sscanf(ptr, "%*c %31s %d %d", format, &n_vars, &n_clauses) < 3) {
                fclose(fp);
                return LOGISAT_ERR_DIMACS_FORMAT;
            }

            if (strcmp(format, "cnf") != 0 || n_vars < 0 || n_clauses < 0) {
                fclose(fp);
                return LOGISAT_ERR_DIMACS_FORMAT;
            }

            expected_vars = (size_t)n_vars;
            expected_clauses = (size_t)n_clauses;
            formula = cnf_formula_create(expected_vars, expected_clauses);
            if (!formula) {
                fclose(fp);
                return LOGISAT_ERR_OUT_OF_MEMORY;
            }
            header_found = true;
            continue;
        }

        if (!header_found) {
            formula = cnf_formula_create(0, 16);
            if (!formula) {
                fclose(fp);
                return LOGISAT_ERR_OUT_OF_MEMORY;
            }
            header_found = true;
        }

        char *token = strtok(ptr, " \t\r\n");
        while (token != NULL) {
            char *endptr = NULL;
            long val = strtol(token, &endptr, 10);
            if (endptr == token) {
                fclose(fp);
                if (current_clause) clause_destroy(current_clause);
                cnf_formula_destroy(formula);
                return LOGISAT_ERR_DIMACS_FORMAT;
            }

            if (val == 0) {
                if (!current_clause) {
                    current_clause = clause_create(4);
                }
                cnf_formula_add_clause(formula, current_clause);
                current_clause = NULL;
            } else {
                if (!current_clause) {
                    current_clause = clause_create(4);
                    if (!current_clause) {
                        fclose(fp);
                        cnf_formula_destroy(formula);
                        return LOGISAT_ERR_OUT_OF_MEMORY;
                    }
                }
                clause_add_literal(current_clause, (int32_t)val);
            }

            token = strtok(NULL, " \t\r\n");
        }
    }

    if (current_clause != NULL) {
        cnf_formula_add_clause(formula, current_clause);
    }

    fclose(fp);
    cnf_formula_update_var_count(formula);
    *out_formula = formula;
    return LOGISAT_OK;
}

logisat_status_t dimacs_save_to_file(const char *filepath, const cnf_formula_t *formula, const char *comment_banner) {
    if (!filepath || !formula) return LOGISAT_ERR_NULL_PTR;

    FILE *fp = fopen(filepath, "w");
    if (!fp) return LOGISAT_ERR_FILE_IO;

    if (comment_banner && strlen(comment_banner) > 0) {
        fprintf(fp, "c %s\n", comment_banner);
    } else {
        fprintf(fp, "c Generated by LogiSAT\n");
    }

    fprintf(fp, "p cnf %zu %zu\n", formula->num_vars, formula->num_clauses);

    for (size_t i = 0; i < formula->num_clauses; ++i) {
        const clause_t *cl = formula->clauses[i];
        for (size_t j = 0; j < cl->size; ++j) {
            fprintf(fp, "%d ", cl->literals[j]);
        }
        fprintf(fp, "0\n");
    }

    fclose(fp);
    return LOGISAT_OK;
}
